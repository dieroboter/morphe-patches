/**
 * The port's binary payloads (adaptive-icon PNGs and the re-encoded sound
 * effects), embedded as Base64 text so the bundle sources stay plain text.
 * Keys are the paths the patches ask for; contents are byte-identical to
 * the files in the port build.
 */
object BundledResources {
    fun read(path: String): ByteArray =
        decodeBase64(DATA[path] ?: throw PatchException("Bundled resource missing from the patch bundle: $path"))

    private fun decodeBase64(data: String): ByteArray {
        val table = IntArray(128) { -1 }
        "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"
            .forEachIndexed { index, c -> table[c.code] = index }
        val out = ArrayList<Byte>(data.length * 3 / 4 + 3)
        var buffer = 0
        var bits = 0
        for (c in data) {
            if (c == '=' || c == '\n' || c == '\r' || c == ' ') continue
            require(c.code < 128 && table[c.code] >= 0) { "Invalid Base64 character in bundled resource" }
            buffer = (buffer shl 6) or table[c.code]
            bits += 6
            if (bits >= 8) {
                bits -= 8
                out.add((buffer shr bits).toByte())
            }
        }
        return ByteArray(out.size) { out[it] }
    }

